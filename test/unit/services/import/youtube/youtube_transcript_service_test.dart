class _FakeHttpException implements Exception {
  final String message;
  const _FakeHttpException(this.message);
  @override
  String toString() => 'FakeHttpException: $message';
}

/// http.Client that just records whether `close()` was called. No requests
/// are routed through it in the dispose-ownership tests, so we only need
/// the close hook.
class _RecordingClient extends http.BaseClient {
  bool closed = false;

  @override
  Future<http.StreamedResponse> send(http.BaseRequest request) async {
    return http.StreamedResponse(
      const Stream.empty(),
      200,
    );
  }

  @override
  void close() {
    closed = true;
    super.close();
  }
}
