// The mockup kit in design/mockup-kit/ is hand-written HTML around one
// generated block per file: the fonts, every token as a CSS variable, the
// type roles as classes, the components in components.css, and every glyph
// in design/assets/icons/ as an SVG symbol. This tool writes that block from the same sources lib/theme/ is
// generated from, so a mockup built from the kit cannot drift from the app
// without CI going red.
//
// Run from the app repo root:
//
//   dart run tools/mockup_kit.dart          rewrite the generated blocks
//   dart run tools/mockup_kit.dart --check  CI: exit 1 when a block is stale

// ignore_for_file: avoid_print

import 'dart:convert';
import 'dart:io';

const _kitDir = 'design/mockup-kit';
const _pages = ['kit.html', 'examples.html', 'designlabb.html'];

const _begin =
    '<!-- BEGIN GENERATED by tools/mockup_kit.dart: '
    'edit design/tokens.json, design/assets/icons/ or components.css, '
    'then run the tool -->';
const _end = '<!-- END GENERATED -->';

// The weights the app's text styles use; the italics are never drawn.
const _fonts = {400: 'Regular', 600: 'Semibold', 700: 'Bold'};

void main(List<String> args) {
  final check = args.contains('--check');
  final block = _generatedBlock();
  var failed = false;

  for (final name in _pages) {
    final file = File('$_kitDir/$name');
    final text = file.readAsStringSync();
    final start = text.indexOf(_begin);
    final stop = text.indexOf(_end);
    if (start < 0 || stop < start) {
      stderr.writeln('KIT-CHECK ${file.path}: generated markers missing');
      failed = true;
      continue;
    }
    final want =
        text.substring(0, start) + block + text.substring(stop + _end.length);
    if (!check) {
      file.writeAsStringSync(want);
      print('wrote ${file.path}');
    } else if (want == text) {
      print('KIT-CHECK ok ${file.path}');
    } else {
      stderr.writeln(
        'KIT-CHECK drift ${file.path}: the generated block does not match '
        'design/. Run dart run tools/mockup_kit.dart and commit the result.',
      );
      failed = true;
    }
  }
  if (failed) exit(1);
}

String _generatedBlock() {
  final tokens =
      jsonDecode(File('design/tokens.json').readAsStringSync())
          as Map<String, dynamic>;
  final out = StringBuffer()
    ..writeln(_begin)
    ..writeln('<style id="butlery-generated">');

  for (final MapEntry(key: weight, value: style) in _fonts.entries) {
    final bytes = File(
      'design/assets/fonts/ButlerySans-0.626-$style.woff2',
    ).readAsBytesSync();
    out.writeln(
      "@font-face{font-family:'ButlerySans';font-weight:$weight;"
      'font-style:normal;src:url(data:font/woff2;base64,'
      "${base64Encode(bytes)}) format('woff2')}",
    );
  }

  // tokens.css is gen-css.mjs output, kept fresh by its own --check in CI.
  final css = File('design/assets/generated/tokens.css').readAsStringSync();
  out.writeln(css.substring(css.indexOf(':root')).trim());

  final roles = (tokens['typography'] as Map)['roles'] as Map;
  for (final MapEntry(key: role, value: r) in roles.entries) {
    final name = _kebab(role as String);
    final rule = StringBuffer('.t-$name{')
      ..write('font-size:var(--butlery-type-$name-size);')
      ..write('font-weight:var(--butlery-type-$name-weight);')
      ..write('line-height:${r['lineHeight']};');
    if (r['tracking'] != null) {
      rule.write('letter-spacing:var(--butlery-type-$name-tracking);');
    }
    if (r['figures'] == 'tabular') {
      rule.write('font-variant-numeric:tabular-nums;');
    }
    out.writeln('$rule}');
  }
  // The hand-written components live once, in components.css, and reach
  // both pages through this block, so the examples cannot fork them.
  out
    ..writeln(File('$_kitDir/components.css').readAsStringSync().trim())
    ..writeln('</style>')
    ..writeln(
      '<svg id="butlery-icons" xmlns="http://www.w3.org/2000/svg" '
      'style="display:none">',
    );

  final icons =
      Directory('design/assets/icons')
          .listSync()
          .whereType<File>()
          .where((f) => f.path.endsWith('.svg'))
          .toList()
        ..sort((a, b) => a.path.compareTo(b.path));
  for (final file in icons) {
    out.writeln(_symbol(file));
  }
  out
    ..writeln('</svg>')
    ..write(_end);
  return out.toString();
}

// The masters carry their paint on the root <svg>; a <symbol> keeps it on a
// <g>. A drawn stroke reads --icon-stroke so a 12-14 px use can take the
// manual's heavier 2.2 stroke without a second copy of the glyph.
String _symbol(File file) {
  final name = file.uri.pathSegments.last.replaceAll('.svg', '');
  final svg = file.readAsStringSync();
  final root = RegExp(r'<svg([^>]*)>').firstMatch(svg)!;
  String attr(String key) =>
      RegExp('\\s$key="([^"]*)"').firstMatch(root.group(1)!)?.group(1) ?? '';
  final body = svg
      .substring(root.end, svg.lastIndexOf('</svg>'))
      .replaceAll(RegExp(r'<title>[^<]*</title>'), '')
      .split('\n')
      .map((l) => l.trim())
      .where((l) => l.isNotEmpty)
      .join();
  final stroke = attr('stroke');
  final paint = StringBuffer('fill="${attr('fill')}" stroke="$stroke"');
  if (stroke != 'none') {
    // --icon-stroke is always in 24 px terms, so a glyph drawn on a larger
    // grid (the 160 px nav icons) scales it to its own units.
    final box = double.tryParse(attr('viewBox').split(' ').last) ?? 24;
    final k = box / 24;
    final base = double.parse(attr('stroke-width'));
    final width = k == 1
        ? 'var(--icon-stroke,${attr('stroke-width')})'
        : 'calc(var(--icon-stroke,${(base / k).toStringAsFixed(2)})*${k.toStringAsFixed(4)})';
    paint.write(
      ' stroke-linecap="${attr('stroke-linecap')}"'
      ' stroke-linejoin="${attr('stroke-linejoin')}"'
      ' style="stroke-width:$width"',
    );
  }
  return '<symbol id="i-$name" viewBox="${attr('viewBox')}">'
      '<g $paint>$body</g></symbol>';
}

String _kebab(String s) => s
    .replaceAllMapped(RegExp('([a-z0-9])([A-Z])'), (m) => '${m[1]}-${m[2]}')
    .replaceAll(RegExp('[._ ]+'), '-')
    .toLowerCase();
