// Kärnflöde steg 0 (Malin 2026-10-30): the repo is the one source for tagging
// words, and the app compiles them as constants so tagging stays synchronous
// and reads no file at run time.
//
// Run from the app repo root:
//
//   dart run tools/gen_tag_vocabulary.dart          regenerate after editing
//                                                   the data file
//   dart run tools/gen_tag_vocabulary.dart --check  red on drift or a hand edit

// ignore_for_file: avoid_print

import 'dart:convert';
import 'dart:io';

const _source = 'lib/services/tagging/config/data/occasions.json';
const _target =
    'lib/services/tagging/config/generated/occasion_vocabulary.g.dart';

Future<void> main(List<String> args) async {
  final check = args.contains('--check');
  final data =
      jsonDecode(File(_source).readAsStringSync()) as Map<String, dynamic>;

  final errors = validate(data);
  if (errors.isNotEmpty) {
    stderr.writeln('$_source is invalid:');
    for (final e in errors) {
      stderr.writeln('  $e');
    }
    exit(1);
  }

  final tmp = Directory.systemTemp.createTempSync('gen_tag_vocabulary');
  try {
    final out = File('${tmp.path}/occasion_vocabulary.g.dart')
      ..writeAsStringSync(render(data));
    final format = await Process.run('dart', ['format', out.path]);
    if (format.exitCode != 0) {
      stderr.write(format.stderr);
      exit(1);
    }
    final generated = out.readAsStringSync();
    final target = File(_target);

    if (check) {
      if (!target.existsSync() || target.readAsStringSync() != generated) {
        stderr.writeln(
          '$_target is out of date with $_source. '
          'Run: dart run tools/gen_tag_vocabulary.dart',
        );
        exit(1);
      }
      print('$_target is up to date');
      return;
    }
    target
      ..createSync(recursive: true)
      ..writeAsStringSync(generated);
    print('wrote $_target');
  } finally {
    tmp.deleteSync(recursive: true);
  }
}

List<String> validate(Map<String, dynamic> data) {
  final errors = <String>[];
  final tags = <String>{};
  final constNames = <String>{};
  for (final group in data.entries) {
    if (group.key.startsWith('_')) continue;
    if (!RegExp(r'^[a-z][a-zA-Z]*$').hasMatch(group.key)) {
      errors.add('group "${group.key}" is not a camelCase name');
    }
    final fields = group.value;
    if (fields is! Map<String, dynamic>) {
      errors.add('${group.key} is not an object');
      continue;
    }
    for (final field in fields.entries) {
      final where = '${group.key}.${field.key}';
      if (!RegExp(r'^[a-z][a-zA-Z]*$').hasMatch(field.key)) {
        errors.add('$where: the field name is not camelCase');
        continue;
      }
      final constName = '${group.key}${_capitalize(field.key)}';
      if (!constNames.add(constName)) {
        errors.add('$where: the name $constName is generated twice');
      }
      final value = field.value;
      final words = value is String ? [value] : value;
      if (words is! List || words.any((w) => w is! String)) {
        errors.add('$where is neither a word nor a list of words');
        continue;
      }
      for (final w in words.cast<String>()) {
        if (w.trim().isEmpty) errors.add('$where holds an empty word');
        if (w != w.toLowerCase()) errors.add('$where: "$w" is not lower case');
        if (w != w.trim()) errors.add('$where: "$w" has outer spaces');
      }
      if (field.key == 'tag' && value is String && !tags.add(value)) {
        errors.add('$where: tag "$value" is used by two groups');
      }
    }
  }
  return errors;
}

String render(Map<String, dynamic> data) {
  final b = StringBuffer()
    ..writeln('// GENERATED by tools/gen_tag_vocabulary.dart from')
    ..writeln('// $_source. Edit that file, not this one.')
    ..writeln()
    ..writeln('abstract final class OccasionVocabulary {');
  final tags = <String>[];
  for (final group in data.entries) {
    if (group.key.startsWith('_')) continue;
    for (final field in (group.value as Map<String, dynamic>).entries) {
      final name = '${group.key}${_capitalize(field.key)}';
      final value = field.value;
      if (value is String) {
        b.writeln('static const $name = ${_quote(value)};');
        if (field.key == 'tag') tags.add(name);
      } else {
        final words = (value as List).cast<String>().map(_quote);
        b.writeln(
          'static const $name = <String>[${words.map((w) => '$w,').join(' ')}];',
        );
      }
    }
  }
  b
    ..writeln()
    ..writeln('/// Every tag name the data file gives Phase 4.')
    ..writeln(
      'static const allTags = <String>{${tags.map((t) => '$t,').join(' ')}};',
    )
    ..writeln('}');
  return b.toString();
}

String _capitalize(String s) => s[0].toUpperCase() + s.substring(1);

String _quote(String s) =>
    "'${s.replaceAll(r'\', r'\\').replaceAll("'", r"\'").replaceAll(r'$', r'\$')}'";
