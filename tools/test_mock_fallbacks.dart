// Generates test/infrastructure/di/generated/production_mock_fallbacks.dart:
// one lazy mocktail mock per type the production DI modules register, so the
// test container needs no hand-written line for a brand-new service.
//
//   dart run tools/test_mock_fallbacks.dart          # rewrite the file
//   dart run tools/test_mock_fallbacks.dart --check  # exit 1 if it is stale
import 'dart:io';

const outputPath =
    'test/infrastructure/di/generated/production_mock_fallbacks.dart';

final _registration = RegExp(r'\.register\w*<([A-Za-z_]\w*)>');
final _optionalProbe = RegExp(r'(?:isRegistered|tryGet)<(?:\w+\.)?([A-Za-z_]\w*)>');
final _declaration = RegExp(
  r'^(abstract |base |final |sealed |interface )*(class|mixin|typedef|enum)\s+([A-Za-z_]\w*)',
  multiLine: true,
);

List<File> _dartFiles(Directory dir) => dir
    .listSync(recursive: true)
    .whereType<File>()
    .where((f) => f.path.endsWith('.dart'))
    .toList()
  ..sort((a, b) => a.path.compareTo(b.path));

/// Production code that branches on `isRegistered`/`tryGet` treats a missing
/// service as "feature off"; a mock would silently flip that branch.
Set<String> _optionalTypes(String root) {
  final result = <String>{};
  for (final f in _dartFiles(Directory('$root/lib'))) {
    if (f.path.contains('/lib/core/di/')) continue;
    for (final m in _optionalProbe.allMatches(f.readAsStringSync())) {
      result.add(m.group(1)!);
    }
  }
  return result;
}

String buildFallbackFile(String root) {
  final registered = <String>{};
  for (final f in _dartFiles(Directory('$root/lib/core/di'))) {
    for (final m in _registration.allMatches(f.readAsStringSync())) {
      registered.add(m.group(1)!);
    }
  }

  final declaredIn = <String, List<String>>{};
  final modifiers = <String, String>{};
  for (final f in _dartFiles(Directory('$root/lib'))) {
    if (f.path.endsWith('.g.dart') || f.path.endsWith('.freezed.dart')) continue;
    final text = f.readAsStringSync();
    if (text.startsWith('part of') || text.contains('\npart of ')) continue;
    for (final m in _declaration.allMatches(text)) {
      final name = m.group(3)!;
      if (!registered.contains(name)) continue;
      final rel = f.path.substring(f.path.indexOf('lib/') + 4);
      declaredIn.putIfAbsent(name, () => []).add(rel);
      modifiers[name] = '${m.group(1) ?? ''}${m.group(2)}';
    }
  }

  final optional = _optionalTypes(root);
  final types = registered.where((t) {
    final where = declaredIn[t];
    if (where == null || where.length != 1) return false;
    if (optional.contains(t)) return false;
    final kind = modifiers[t]!;
    return kind.endsWith('class') &&
        !kind.contains('final') &&
        !kind.contains('base') &&
        !kind.contains('sealed');
  }).toList()
    ..sort();

  final b = StringBuffer()
    ..writeln('// GENERATED by tools/test_mock_fallbacks.dart. Do not edit.')
    ..writeln('// ignore_for_file: type=lint')
    ..writeln("import 'package:get_it/get_it.dart';")
    ..writeln("import 'package:mocktail/mocktail.dart';");
  for (var i = 0; i < types.length; i++) {
    b.writeln("import 'package:butlery/${declaredIn[types[i]]!.single}' as p$i;");
  }
  b.writeln();
  for (var i = 0; i < types.length; i++) {
    b.writeln('class _M$i extends Mock implements p$i.${types[i]} {}');
  }
  b
    ..writeln()
    ..writeln('void registerProductionMockFallbacks(GetIt getIt) {');
  for (var i = 0; i < types.length; i++) {
    b
      ..writeln('  if (!getIt.isRegistered<p$i.${types[i]}>()) {')
      ..writeln('    getIt.registerLazySingleton<p$i.${types[i]}>(_M$i.new);')
      ..writeln('  }');
  }
  b.writeln('}');
  return b.toString();
}

void main(List<String> args) {
  final text = buildFallbackFile('.');
  final out = File(outputPath);
  if (args.contains('--check')) {
    final current = out.existsSync() ? out.readAsStringSync() : '';
    if (current != text) {
      stderr.writeln('$outputPath is stale: run dart run tools/test_mock_fallbacks.dart');
      exit(1);
    }
    return;
  }
  out.createSync(recursive: true);
  out.writeAsStringSync(text);
}
