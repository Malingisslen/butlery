/// Dialog for viewing and managing all recipe tags.
///
/// Allows users to:
/// - View all effective tags (auto-generated + user-added)
/// - Remove tags they don't want
/// - Add custom tags
///
/// Returns the updated [TagOverrides] when saved, or null if cancelled.
class TagEditorDialog extends StatefulWidget {
  final Recipe recipe;

  const TagEditorDialog({
    super.key,
    required this.recipe,
  });

  /// Shows the tag editor dialog and returns updated overrides if saved.
  static Future<TagOverrides?> show(BuildContext context, Recipe recipe) {
    return showButleryDialog<TagOverrides>(
      context: context,
      builder: (context) => TagEditorDialog(recipe: recipe),
    );
  }

  @override
  State<TagEditorDialog> createState() => _TagEditorDialogState();
}

class _TagEditorDialogState extends State<TagEditorDialog> {
  late Set<String> _addedTags;
  late Set<String> _removedTags;
  final _newTagController = TextEditingController();
  final _formKey = GlobalKey<FormState>();

  @override
  void initState() {
    super.initState();
    _addedTags = Set.from(widget.recipe.tagOverrides?.addedTags ?? {});
    _removedTags = Set.from(widget.recipe.tagOverrides?.removedTags ?? {});
  }

  @override
  void dispose() {
    _newTagController.dispose();
    super.dispose();
  }

  /// Auto-generated tags from the tagging system.
  Set<String> get _autoGeneratedTags => widget.recipe.tagResult?.tags ?? {};

  /// All effective tags currently visible.
  Set<String> get _effectiveTags {
    return _autoGeneratedTags.union(_addedTags).difference(_removedTags);
  }

  /// Checks if a tag is user-added.
  bool _isUserAdded(String tag) => _addedTags.contains(tag);

  void _removeTag(String tag) {
    setState(() {
      if (_addedTags.contains(tag)) {
        // User-added tag: just remove from addedTags
        _addedTags.remove(tag);
      } else {
        // Auto-generated tag: add to removedTags
        _removedTags.add(tag);
      }
    });
  }

  void _restoreTag(String tag) {
    setState(() {
      _removedTags.remove(tag);
    });
  }

  void _addNewTag() {
    if (!_formKey.currentState!.validate()) return;

    final newTag = _newTagController.text.trim().toLowerCase();
    if (newTag.isEmpty) return;

    // Don't add duplicates
    if (_effectiveTags.contains(newTag)) {
      // The ink snackbar (PQ-09 = A).
      SnackBarUtils.showInfo(context, context.l10n.tagAlreadyExists);
      return;
    }

    setState(() {
      _addedTags.add(newTag);
      // If tag was in removedTags, restore it
      _removedTags.remove(newTag);
    });

    _newTagController.clear();
  }

  void _save() {
    final overrides = TagOverrides(
      addedTags: _addedTags,
      removedTags: _removedTags,
      allergenOverrides:
          widget.recipe.tagOverrides?.allergenOverrides ?? const {},
      dietaryOverrides:
          widget.recipe.tagOverrides?.dietaryOverrides ?? const {},
      lastEditedAt: clock.now(),
    );
    Navigator.of(context).pop(overrides);
  }

  @override
  Widget build(BuildContext context) {
    final cs = Theme.of(context).colorScheme;
    final sortedTags = _effectiveTags.toList()..sort();
    final removedTagsList = _removedTags.toList()..sort();

    return ButleryDialogFrame(
      maxHeight: AppDimensions.dialogMaxHeightMedium,
      padding: const EdgeInsets.all(AppDimensions.space16),
      child: Column(
        mainAxisSize: MainAxisSize.min,
        crossAxisAlignment: CrossAxisAlignment.start,
        children: [
          Row(
            children: [
              ButleryIcon(
                ButleryIcons.tag,
                color: cs.onPrimaryContainer,
                size: AppDimensions.iconSizeM,
              ),
              const SizedBox(width: AppDimensions.space8),
              Semantics(
                header: true,
                child: Text(
                  context.l10n.tagManageTags,
                  style: AppTextStyles.titleLarge,
                ),
              ),
              const Spacer(),
              ButleryCloseButton(semanticLabel: context.l10n.commonClose),
            ],
          ),
          const ButleryDivider(spacing: AppDimensions.space32),

          Flexible(
            child: SingleChildScrollView(
              child: Column(
                crossAxisAlignment: CrossAxisAlignment.start,
                children: [
                  if (sortedTags.isNotEmpty) ...[
                    Semantics(
                      header: true,
                      child: Text(
                        context.l10n.tagActiveTags,
                        style: AppTextStyles.titleSmall,
                      ),
                    ),
                    const SizedBox(height: AppDimensions.space4),
                    Wrap(
                      spacing: AppDimensions.space4,
                      runSpacing: AppDimensions.space4,
                      children: sortedTags
                          .map((tag) => _buildTagChip(tag))
                          .toList(),
                    ),
                    const SizedBox(height: AppDimensions.space12),
                  ],

                  if (removedTagsList.isNotEmpty) ...[
                    Semantics(
                      header: true,
                      child: Text(
                        context.l10n.tagRemovedTags,
                        style: AppTextStyles.titleSmall.copyWith(
                          color: cs.onSurfaceVariant,
                        ),
                      ),
                    ),
                    const SizedBox(height: AppDimensions.space4),
                    Wrap(
                      spacing: AppDimensions.space4,
                      runSpacing: AppDimensions.space4,
                      children: removedTagsList
                          .map((tag) => _buildRemovedTagChip(tag))
                          .toList(),
                    ),
                    const SizedBox(height: AppDimensions.space12),
                  ],

                  Semantics(
                    header: true,
                    child: Text(
                      context.l10n.tagAddNewTag,
                      style: AppTextStyles.titleSmall,
                    ),
                  ),
                  const SizedBox(height: AppDimensions.space4),
                  Form(
                    key: _formKey,
                    child: Row(
                      children: [
                        Expanded(
                          child: StyledInput(
                            // The section heading above already stands where a label would,
                            // so the field takes its name for screen readers only.
                            semanticLabel: context.l10n.tagAddNewTag,
                            controller: _newTagController,
                            hint: context.l10n.tagWriteTagHint,
                            contentPadding: const EdgeInsets.symmetric(
                              horizontal: AppDimensions.space12,
                              vertical: AppDimensions.space8,
                            ),
                            validator: (value) {
                              if (value == null || value.trim().isEmpty) {
                                return context.l10n.tagEnterTag;
                              }
                              if (value.trim().length < 2) {
                                return context.l10n.tagMinTwoChars;
                              }
                              return null;
                            },
                            onSubmitted: (_) => _addNewTag(),
                          ),
                        ),
                        const SizedBox(width: AppDimensions.space4),
                        AppIconButton(
                          icon: ButleryIcons.plus,
                          semanticLabel: context.l10n.tagAddTag,
                          onPressed: _addNewTag,
                          filled: true,
                        ),
                      ],
                    ),
                  ),
                ],
              ),
            ),
          ),

          const SizedBox(height: AppDimensions.space12),
          const ButleryDivider(),
          const SizedBox(height: AppDimensions.space8),

          // OverflowBar hands the buttons loose constraints, which the
          // theme's infinite minimum button width needs; a Row would not.
          OverflowBar(
            alignment: MainAxisAlignment.end,
            spacing: AppDimensions.space8,
            children: [
              const DialogCancelButton(),
              ButleryDialogPrimary(
                label: context.l10n.commonSave,
                onPressed: _save,
              ),
            ],
          ),
        ],
      ),
    );
  }

  Widget _buildTagChip(String tag) {
    final isUserAdded = _isUserAdded(tag);
    final displayName = TagDisplayUtils.getDisplayName(tag);

    return ButleryRemovableChip(
      label: displayName,
      removeLabel: context.l10n.commonRemove,
      onRemove: () => _removeTag(tag),
      icon: isUserAdded ? ButleryIcons.user : null,
      tooltip: isUserAdded
          ? context.l10n.tagManuallyAdded
          : context.l10n.tagAutoGenerated,
    );
  }

  Widget _buildRemovedTagChip(String tag) {
    return ButleryActionChip(
      label: TagDisplayUtils.getDisplayName(tag),
      icon: ButleryIcons.undo,
      struckThrough: true,
      onPressed: () => _restoreTag(tag),
      tooltip: context.l10n.tagClickToRestore,
    );
  }
}
